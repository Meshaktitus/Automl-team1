"""Generates TypeScript interfaces from the two profiling JSON Schemas, so Team 3's types always match the contract.
Usage:  python schema_to_typescript.py          (writes profiling.types.ts)
Handles the schema keywords we use: $ref, type (single or list), enum, const, oneOf, properties, required,
additionalProperties, items. Validation-only keywords (minimum, minLength, if/then ...) are not representable in
TypeScript types and are noted in comments where they matter.
"""
import json
from datetime import date
from pathlib import Path

HERE = Path(__file__).parent
SCALAR = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def pascal(name):
    return "Profiling" + name[0].upper() + name[1:]


def comment(text, pad):
    return f"{pad}/** {text.strip()} */\n" if text else ""


def ts_type(schema, defs_prefix_map, pad):
    if "$ref" in schema:
        return defs_prefix_map[schema["$ref"].split("/")[-1]]
    if "oneOf" in schema:
        return " | ".join(ts_type(s, defs_prefix_map, pad) for s in schema["oneOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**schema, "type": x}, defs_prefix_map, pad) for x in t)
    if t == "array":
        inner = ts_type(schema.get("items", {}), defs_prefix_map, pad)
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if t == "object":
        return object_body(schema, defs_prefix_map, pad)
    return SCALAR[t]


def object_body(schema, defs, pad):
    props, required = schema.get("properties"), set(schema.get("required", []))
    if not props:
        extra = schema.get("additionalProperties")
        value = ts_type(extra, defs, pad) if isinstance(extra, dict) else "unknown"
        return f"{{ [key: string]: {value} }}"
    lines = ["{"]
    for name, sub in props.items():
        lines.append(comment(sub.get("description"), pad + "  ").rstrip("\n") if sub.get("description") else "")
        lines.append(f"{pad}  {name}{'' if name in required else '?'}: {ts_type(sub, defs, pad + '  ')};")
    lines.append(pad + "}")
    return "\n".join(l for l in lines if l != "")


def generate(path, root_name):
    schema = json.loads(path.read_text(encoding="utf-8"))
    defs = {k: pascal(k) for k in schema.get("$defs", {})}
    out = [f"// ---- {path.name} ----\n"]
    for key, sub in schema.get("$defs", {}).items():
        out.append(comment(sub.get("description"), "") + f"export interface {defs[key]} {object_body(sub, defs, '')}\n")
    out.append(comment(schema.get("description"), "") + f"export interface {root_name} {object_body(schema, defs, '')}\n")
    return "\n".join(out)


header = (f"// Generated by schema_to_typescript.py from schemas/*.schema.json ({date.today().isoformat()}). Contract v1.0-draft: proposed, not final.\n"
          "// Do not edit by hand: change the schema and regenerate.\n"
          "// Notes: optional (?) fields are ABSENT from the JSON when they do not apply, not null. snake_case names are as sent by the module;\n"
          "// any camelCase conversion is the consumer's choice. Value ranges (for example missing_pct 0 to 100) are in the schema, not in these types.\n"
          "// A failed response has dataset: null, columns: [] and at least one error; a non-failed response has errors: [].\n\n")
text = header + generate(HERE / "schemas" / "profiling_request.schema.json", "ProfilingRequest") + "\n" \
    + generate(HERE / "schemas" / "profiling_response.schema.json", "ProfilingResponse")
(HERE / "profiling.types.ts").write_text(text, encoding="utf-8")
print("Written: profiling.types.ts")
